"""
European club competitions (CL, EL, ECL) from FotMob: results, 90-minute
scores, stage/leg and xG, 21-22 onwards.

Each competition and season is cached in data/raw/<Div>/fotmob_<s>.csv,
one row per finished match, in FotMob's own team names and ids (the
league ids are in competitions.py). load_european() turns the caches into
all_matches-style rows: canonical club names, each club's domestic league
that season, a neutral-venue flag and the 90-minute result.

FotMob's scoreStr includes extra time, so the 90-minute score comes from
the "Half" event at 90' and the 90-minute xG from the FirstHalf +
SecondHalf periods ("All" includes extra time too).

    python src/tools/backfill_europe.py     # fill the caches
"""

import math
import re
import time
from pathlib import Path

import pandas as pd
import requests

import competitions
from load_data import (
    FOTMOB_CHECKPOINT_EVERY,
    FOTMOB_DELAY,
    FOTMOB_HEADERS,
    FOTMOB_REFETCH_DAYS,
    OUTPUT_PATH,
    RAW_DIR,
    _fotmob_get,
    competition_dir,
)
from team_names import REFERENCE_PATH, load_country_map, load_id_map

EUROPEAN = ["CL", "EL", "ECL"]

# The COVID seasons 19-20 and 20-21 are left out (D3); the Conference
# League started in 21-22, so every competition's history lines up
FIRST_SEASON = "21-22"

# The league phase replaced the group stage in 24-25
LEAGUE_PHASE_FROM = "24-25"

# FotMob's non-numeric rounds. Its fixture list calls the knockout
# play-off "playoff" while matchDetails calls the same tie "1/16".
KNOCKOUT_STAGES = {
    "playoff": "KO_PLAYOFF",
    "1/16": "KO_PLAYOFF",
    "1/8": "R16",
    "1/4": "QF",
    "1/2": "SF",
    "final": "FINAL",
}

CACHE_COLUMNS = [
    "MatchId", "Date", "Stage", "Round", "Leg", "HomeId", "AwayId",
    "HomeTeam", "AwayTeam", "FTHG90", "FTAG90", "FTHG", "FTAG", "Reason",
    "AggHome", "AggAway", "PenWinner", "TieWinner",
    "HomeXG90", "AwayXG90", "HomeXGAll", "AwayXGAll",
    "StadiumLat", "StadiumLon",
]

# Every club seen in a European cache: country (for clubs outside the
# modelled leagues, HomeLeague "X:<country>") and home ground (for the
# neutral flag). Generated by backfill_europe.py; a missing country can
# be filled in by hand.
TEAMS_PATH = RAW_DIR / "fotmob_teams.csv"
TEAM_COLUMNS = ["FotMobId", "Name", "Country", "Venue", "VenueLat", "VenueLon"]

# A home match is neutral when it's played abroad (Ukrainian clubs since
# 22-23, Israeli clubs since October 2023), not when it's moved within the
# country (Kairat's winter games in Astana). FotMob's stadium country is
# often blank, so a stadium's country is that of the nearest club ground
# in fotmob_teams.csv, unless it's listed in STADIUMS_PATH: hand-checked
# stadiums near a border, where the nearest ground is a foreign club's
# (Klagenfurt is nearer Ljubljana than Graz). The final is always neutral.
STADIUMS_PATH = REFERENCE_PATH.replace("team_names.csv", "stadium_countries.csv")
STADIUM_MATCH_KM = 5
COLUMNS = [
    "Div", "Season", "Date", "Stage", "Round", "Leg", "Neutral", "MatchId",
    "HomeTeam", "AwayTeam", "HomeLeague", "AwayLeague",
    "FTHG", "FTAG", "FTR", "AETHG", "AETAG", "PenWinner", "TieWinner",
    "AggHome", "AggAway", "HomeXG", "AwayXG", "XGSource",
]

CACHE_FILE_RE = re.compile(r"fotmob_(\d{2}-\d{2})\.csv$")


def fotmob_season(season):
    """"24-25" -> "2024/2025", FotMob's season name."""

    return f"20{season[:2]}/20{season[3:]}"


# ============================================================
# PARSING (pure: one FotMob response in, plain values out)
# ============================================================

def stage_and_round(fotmob_round, season):
    """(Stage, Round) for a FotMob round, e.g. ("3", "24-25") -> ("LEAGUE_PHASE", "MD3")."""

    fotmob_round = str(fotmob_round)

    if fotmob_round.isdigit():
        stage = "LEAGUE_PHASE" if season >= LEAGUE_PHASE_FROM else "GROUP"
        return stage, f"MD{fotmob_round}"

    try:
        stage = KNOCKOUT_STAGES[fotmob_round]
    except KeyError:
        raise ValueError(
            f"Unknown FotMob round {fotmob_round!r} in {season}; "
            f"add it to KNOCKOUT_STAGES"
        ) from None

    return stage, stage


def _playoff_legs(league):
    """MatchId -> leg (1 or 2) for every two-legged tie in the bracket."""

    legs = {}

    for knockout_round in (league.get("playoff") or {}).get("rounds", []):
        for matchup in knockout_round.get("matchups", []):

            if matchup.get("bestOf") != 2:
                continue

            matches = sorted(
                matchup.get("matches", []), key=lambda m: m["status"]["utcTime"]
            )
            for leg, match in enumerate(matches, start=1):
                legs[str(match["matchId"])] = leg

    return legs


def parse_fixtures(league, season):
    """
    One dict per finished match in a FotMob ``leagues`` response: id,
    date, stage, round, leg and both teams. Qualifiers aren't in FotMob's
    competition fixture lists, so nothing needs filtering out for them.
    """

    legs = _playoff_legs(league)
    rows = []

    for match in league["fixtures"]["allMatches"]:

        status = match["status"]
        if (
            not status.get("finished")
            or status.get("cancelled")
            or status.get("awarded")
        ):
            continue

        stage, round_ = stage_and_round(match["round"], season)

        rows.append({
            "MatchId": str(match["id"]),
            "Date": status["utcTime"][:10],
            "Stage": stage,
            "Round": round_,
            "Leg": legs.get(str(match["id"])),
            "HomeId": int(match["home"]["id"]),
            "AwayId": int(match["away"]["id"]),
            "HomeTeam": match["home"]["name"],
            "AwayTeam": match["away"]["name"],
        })

    return rows


def _score(score_str):
    """"3 - 1" -> (3, 1)."""

    home, away = score_str.split(" - ")
    return int(home), int(away)


def _period_xg(details, period):
    """(home xG, away xG) for one FotMob stats period, or (None, None)."""

    try:
        stats = details["content"]["stats"]["Periods"][period]["stats"][0]["stats"]
    except (KeyError, IndexError, TypeError):
        return None, None

    for stat in stats:
        if stat.get("key") == "expected_goals":
            home_xg, away_xg = stat["stats"]
            return float(home_xg), float(away_xg)

    return None, None


def parse_match_details(details):
    """
    The result fields of one FotMob ``matchDetails`` response: 90-minute
    and final score, how it ended (FT/AET/Pen), aggregate, penalty and
    tie winner ("H"/"A"), 90-minute and full xG, leg and stadium. None if
    an extra-time match has no 90-minute score to read.
    """

    status = details["header"]["status"]
    home_name = details["header"]["teams"][0]["name"]
    reason = status["reason"]["short"]
    fthg, ftag = _score(status["scoreStr"])

    if reason == "FT":
        fthg90, ftag90 = fthg, ftag
    else:
        events = details["content"]["matchFacts"]["events"]["events"]
        full_time = [
            e for e in events if e.get("type") == "Half" and e.get("time") == 90
        ]
        if not full_time:
            return None
        fthg90, ftag90 = full_time[0]["homeScore"], full_time[0]["awayScore"]

    home_all, away_all = _period_xg(details, "All")
    first_home, first_away = _period_xg(details, "FirstHalf")
    second_home, second_away = _period_xg(details, "SecondHalf")

    if first_home is not None and second_home is not None:
        home_xg90 = round(first_home + second_home, 2)
        away_xg90 = round(first_away + second_away, 2)
    elif reason == "FT":
        home_xg90, away_xg90 = home_all, away_all
    else:
        home_xg90 = away_xg90 = None

    def side_beating(loser):
        if not loser:
            return None
        return "A" if loser == home_name else "H"

    aggregate = status.get("aggregatedStr")
    agg_home, agg_away = _score(aggregate) if aggregate else (None, None)

    info = details["content"]["matchFacts"].get("infoBox") or {}
    leg_info = info.get("legInfo") or {}
    stadium = info.get("Stadium") or {}

    return {
        "FTHG90": fthg90,
        "FTAG90": ftag90,
        "FTHG": fthg,
        "FTAG": ftag,
        "Reason": reason,
        "AggHome": agg_home,
        "AggAway": agg_away,
        "PenWinner": side_beating(status.get("whoLostOnPenalties")),
        "TieWinner": side_beating(status.get("whoLostOnAggregated")),
        "HomeXG90": home_xg90,
        "AwayXG90": away_xg90,
        "HomeXGAll": home_all,
        "AwayXGAll": away_all,
        "Leg": leg_info.get("bestOfNum") if leg_info.get("bestOf") == 2 else None,
        "StadiumLat": stadium.get("lat"),
        "StadiumLon": stadium.get("long"),
    }


def match_row(fixture, details):
    """A cache row from a parse_fixtures() row and its matchDetails, or None."""

    result = parse_match_details(details)

    if result is None:
        return None

    row = {**fixture, **result, "Leg": result["Leg"] or fixture["Leg"]}

    # Aggregate and tie winner belong to the second leg (and the final)
    if row["Leg"] != 2:
        row["AggHome"] = row["AggAway"] = row["TieWinner"] = None

    if row["Stage"] == "FINAL":
        row["TieWinner"] = row["PenWinner"] or (
            "H" if row["FTHG"] > row["FTAG"] else "A"
        )

    return {column: row.get(column) for column in CACHE_COLUMNS}


def parse_team(team):
    """A fotmob_teams.csv row from one FotMob ``teams`` response."""

    widget = ((team.get("overview") or {}).get("venue") or {}).get("widget") or {}
    lat, lon = (widget.get("location") or [None, None])[:2]

    return {
        "FotMobId": int(team["details"]["id"]),
        "Name": team["details"]["name"],
        "Country": team["details"].get("country") or None,
        "Venue": widget.get("name"),
        "VenueLat": float(lat) if lat else None,
        "VenueLon": float(lon) if lon else None,
    }


# ============================================================
# FETCHING (serial, FOTMOB_DELAY apart, resumable)
# ============================================================

def _session():

    session = requests.Session()
    session.headers.update(FOTMOB_HEADERS)

    return session


def read_cache(cache_path):

    if not cache_path.exists():
        return pd.DataFrame(columns=CACHE_COLUMNS)

    return pd.read_csv(cache_path, dtype={"MatchId": str})


def fetch_season(div, season, raw_dir=RAW_DIR, session=None):
    """
    Bring one competition season's cache up to date and return
    (cache, number of finished matches FotMob lists). FotMob's whole
    fixture list for the season goes to fixtures_<season>.csv alongside.

    Matches already cached are kept, except those from the last
    FOTMOB_REFETCH_DAYS (Opta still revises their xG), so a re-run only
    requests what's missing. A match that fails is left out and retried
    next time. Progress is saved every FOTMOB_CHECKPOINT_EVERY matches.
    """

    session = session or _session()
    cache_path = competition_dir(div, raw_dir) / f"fotmob_{season}.csv"
    cache_path.parent.mkdir(parents=True, exist_ok=True)

    cached = read_cache(cache_path)
    cutoff = (
        pd.Timestamp.now(tz="UTC").tz_localize(None).normalize()
        - pd.Timedelta(days=FOTMOB_REFETCH_DAYS)
    )
    cached = cached[pd.to_datetime(cached["Date"]) < cutoff]
    have = set(cached["MatchId"])

    league = _fotmob_get(
        session,
        "leagues",
        {"id": competitions.get(div)["fotmob"], "season": fotmob_season(season)},
    )
    fixtures = parse_fixtures(league, season)

    # The whole fixture list too, played or not: CL fixtures from
    # football-data.org are matched to FotMob's clubs through it
    import champions_league  # it imports this module

    champions_league.parse_fixture_list(league).to_csv(
        champions_league.fixture_list_path(div, season, raw_dir), index=False
    )

    rows = []

    def combined():
        return (
            pd.concat([cached, pd.DataFrame(rows, columns=CACHE_COLUMNS)], ignore_index=True)
            .sort_values(["Date", "MatchId"])
            .reset_index(drop=True)[CACHE_COLUMNS]
        )

    for fixture in fixtures:

        if fixture["MatchId"] in have:
            continue

        try:
            details = _fotmob_get(
                session, "matchDetails", {"matchId": fixture["MatchId"]}
            )
        except requests.RequestException as exc:
            print(f"WARNING: FotMob match {fixture['MatchId']} failed ({exc})")
            continue
        finally:
            time.sleep(FOTMOB_DELAY)

        row = match_row(fixture, details)

        if row is None:
            print(
                f"WARNING: no 90-minute score for {div} {season} "
                f"{fixture['HomeTeam']} v {fixture['AwayTeam']} ({fixture['MatchId']})"
            )
            continue

        rows.append(row)

        if len(rows) % FOTMOB_CHECKPOINT_EVERY == 0:
            combined().to_csv(cache_path, index=False)

    cache = combined()
    cache.to_csv(cache_path, index=False)

    return cache, len(fixtures)


def read_teams(teams_path=TEAMS_PATH):

    if not teams_path.exists():
        return pd.DataFrame(columns=TEAM_COLUMNS)

    return pd.read_csv(teams_path, dtype={"FotMobId": int})


def fetch_teams(team_ids, teams_path=TEAMS_PATH, session=None):
    """Add country and home ground for any of ``team_ids`` not in teams_path yet."""

    session = session or _session()
    teams = read_teams(teams_path)
    missing = sorted(set(int(i) for i in team_ids) - set(teams["FotMobId"]))

    rows = []

    for n, team_id in enumerate(missing, start=1):

        try:
            rows.append(parse_team(_fotmob_get(session, "teams", {"id": team_id})))
        except (requests.RequestException, KeyError) as exc:
            print(f"WARNING: FotMob team {team_id} failed ({exc})")
        finally:
            time.sleep(FOTMOB_DELAY)

        if rows and (n % FOTMOB_CHECKPOINT_EVERY == 0 or n == len(missing)):
            teams_path.parent.mkdir(parents=True, exist_ok=True)
            pd.concat(
                [teams, pd.DataFrame(rows, columns=TEAM_COLUMNS)], ignore_index=True
            ).sort_values("FotMobId").to_csv(teams_path, index=False)

    return read_teams(teams_path)


# ============================================================
# LOADING (caches -> all_matches-style rows)
# ============================================================

def load_cache(divs=EUROPEAN, raw_dir=RAW_DIR):
    """Every cached season of ``divs``, with Div and Season added."""

    frames = []

    for div in divs:
        for path in sorted(competition_dir(div, raw_dir).glob("fotmob_*.csv")):

            found = CACHE_FILE_RE.search(path.name)
            if not found or found.group(1) < FIRST_SEASON:
                continue

            frames.append(read_cache(path).assign(Div=div, Season=found.group(1)))

    if not frames:
        return pd.DataFrame(columns=["Div", "Season", *CACHE_COLUMNS])

    return pd.concat(frames, ignore_index=True)


def _distance_km(lat1, lon1, lat2, lon2):
    """Great-circle distance (haversine)."""

    lat1, lon1, lat2, lon2 = map(math.radians, (lat1, lon1, lat2, lon2))
    a = (
        math.sin((lat2 - lat1) / 2) ** 2
        + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    )

    return 2 * 6371 * math.asin(math.sqrt(a))


def _club_names(raw, id_map, teams):
    """
    FotMob id -> the name the club goes by: its canonical name if
    team_names.csv has its fotmob_id, else FotMob's. Raises if an
    unmapped club's FotMob name would collide with another club.
    """

    seen = pd.concat([
        raw[["HomeId", "HomeTeam"]].set_axis(["Id", "Name"], axis=1),
        raw[["AwayId", "AwayTeam"]].set_axis(["Id", "Name"], axis=1),
    ]).drop_duplicates("Id", keep="last")
    fotmob_names = dict(zip(seen["Id"].astype(int), seen["Name"]))
    fotmob_names.update(dict(zip(teams["FotMobId"], teams["Name"])))

    names = {
        team_id: id_map.get(team_id, name) for team_id, name in fotmob_names.items()
    }

    taken = pd.Series(names).value_counts()
    clashes = sorted(taken[taken > 1].index)

    if clashes:
        raise ValueError(
            f"European clubs share a name: {clashes}. Give the unmapped one a "
            f"row (with its fotmob_id) in {REFERENCE_PATH}."
        )

    return names


def results_for_elo(domestic, raw_dir=RAW_DIR, before=None):
    """
    load_european() rows for the shared-scale Elo, matched to the
    ``domestic`` frame being rated (only matches dated before ``before``,
    when given). If the caches can't be read the leagues are rated on
    their own (None), with a warning, rather than failing the run.
    """

    try:
        matches = load_european(domestic=domestic, raw_dir=raw_dir)
    except (ValueError, OSError) as exc:
        print(f"WARNING: European results unavailable ({exc}); rating each league on its own")
        return None

    if before is not None:
        matches = matches[matches["Date"] < pd.Timestamp(before).normalize()]

    return matches.reset_index(drop=True)


def load_european(
    divs=EUROPEAN,
    domestic=None,
    raw_dir=RAW_DIR,
    teams_path=TEAMS_PATH,
    reference_path=REFERENCE_PATH,
    stadiums_path=STADIUMS_PATH,
):
    """
    Every cached European match as one all_matches-style row (plan §3.1).

    FTHG/FTAG/FTR and HomeXG/AwayXG are the 90-minute values;
    AETHG/AETAG are the score after extra time (NaN if there wasn't any).
    HomeLeague/AwayLeague are the club's Div that season in ``domestic``
    (default: data/processed/all_matches.csv), else "X:<country>".
    """

    raw = load_cache(divs, raw_dir)
    teams = read_teams(teams_path)

    if raw.empty:
        return pd.DataFrame(columns=COLUMNS)

    id_map = load_id_map(reference_path=reference_path)
    names = _club_names(raw, id_map, teams)

    countries = load_country_map(reference_path=reference_path)
    fotmob_countries = dict(zip(teams["FotMobId"], teams["Country"]))
    grounds = [
        (row.VenueLat, row.VenueLon, row.Country)
        for row in teams.itertuples()
        if pd.notna(row.VenueLat) and pd.notna(row.VenueLon) and pd.notna(row.Country)
    ]

    def country(team_id):
        if team_id in id_map:
            return countries.get(id_map[team_id])
        return fotmob_countries.get(team_id)

    team_ids = set(raw["HomeId"].astype(int)) | set(raw["AwayId"].astype(int))
    no_country = sorted(
        names[i] for i in team_ids if not isinstance(country(i), str)
    )

    if no_country:
        raise ValueError(
            f"No country for European club(s) {no_country}. Run "
            f"src/tools/backfill_europe.py, or fill in Country in {teams_path}."
        )

    if domestic is None:
        domestic = (
            pd.read_csv(OUTPUT_PATH, usecols=["Div", "Season", "HomeTeam", "AwayTeam"])
            if OUTPUT_PATH.exists()
            else pd.DataFrame(columns=["Div", "Season", "HomeTeam", "AwayTeam"])
        )

    leagues = [
        div for div, entry in competitions.COMPETITIONS.items()
        if entry["kind"] == "league"
    ]
    in_league = domestic[domestic["Div"].isin(leagues)]
    league_of = {
        (season, team): div
        for side in ("HomeTeam", "AwayTeam")
        for div, season, team in zip(in_league["Div"], in_league["Season"], in_league[side])
    }

    def home_league(season, team_id):
        return league_of.get((season, names[team_id]), f"X:{country(team_id)}")

    stadiums = pd.read_csv(stadiums_path) if Path(stadiums_path).exists() else None
    known_stadiums = (
        [] if stadiums is None
        else list(zip(stadiums["lat"], stadiums["lon"], stadiums["country"]))
    )

    def neutral(match):
        if match.Stage == "FINAL":
            return 1
        if not grounds or pd.isna(match.StadiumLat) or pd.isna(match.StadiumLon):
            return 0

        def nearest(places):
            return min(
                (_distance_km(lat, lon, match.StadiumLat, match.StadiumLon), country)
                for lat, lon, country in places
            )

        km, stadium_country = nearest(known_stadiums) if known_stadiums else (None, None)
        if km is None or km > STADIUM_MATCH_KM:
            _, stadium_country = nearest(grounds)

        # FotMob's codes on both sides (team_names.csv may spell some differently)
        return int(stadium_country != fotmob_countries.get(int(match.HomeId)))

    home_ids = raw["HomeId"].astype(int)
    away_ids = raw["AwayId"].astype(int)
    extra_time = raw["Reason"].isin(["AET", "Pen"])

    def winner_name(side):
        return [
            names[h] if s == "H" else names[a] if s == "A" else None
            for s, h, a in zip(raw[side], home_ids, away_ids)
        ]

    matches = pd.DataFrame({
        "Div": raw["Div"],
        "Season": raw["Season"],
        "Date": pd.to_datetime(raw["Date"]),
        "Stage": raw["Stage"],
        "Round": raw["Round"],
        "Leg": raw["Leg"].astype("Int64"),
        "Neutral": [neutral(m) for m in raw.itertuples()],
        "MatchId": raw["MatchId"],
        "HomeTeam": home_ids.map(names),
        "AwayTeam": away_ids.map(names),
        "HomeLeague": [home_league(s, i) for s, i in zip(raw["Season"], home_ids)],
        "AwayLeague": [home_league(s, i) for s, i in zip(raw["Season"], away_ids)],
        "FTHG": raw["FTHG90"].astype(int),
        "FTAG": raw["FTAG90"].astype(int),
        "AETHG": raw["FTHG"].where(extra_time).astype("Int64"),
        "AETAG": raw["FTAG"].where(extra_time).astype("Int64"),
        "PenWinner": winner_name("PenWinner"),
        "TieWinner": winner_name("TieWinner"),
        "AggHome": raw["AggHome"].astype("Int64"),
        "AggAway": raw["AggAway"].astype("Int64"),
        "HomeXG": raw["HomeXG90"],
        "AwayXG": raw["AwayXG90"],
    })

    matches["FTR"] = [
        "H" if h > a else "A" if a > h else "D"
        for h, a in zip(matches["FTHG"], matches["FTAG"])
    ]
    matches["XGSource"] = (
        matches["HomeXG"].notna() & matches["AwayXG"].notna()
    ).map({True: "FotMob", False: None})

    return (
        matches[COLUMNS]
        .sort_values(["Date", "Div", "MatchId"])
        .reset_index(drop=True)
    )
